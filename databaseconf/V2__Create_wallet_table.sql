CREATE TABLE Wallet(
	id INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,	-- id is autogenerated
	name VARCHAR(255) NOT NULL,			-- name with which the user can choose his wallet
	network INTEGER NOT NULL,			-- Netzwork saved as enum
	prkey CHAR(48),					-- private Bitcoin Master Key (32 Byte) -> After Decryption with AES 32 Byte + 16 Byte
	xpub TEXT,					-- public Key or Bitcoin address
	user INTEGER NOT NULL,				-- User who owns Wallet
	FOREIGN KEY (user) REFERENCES User(id)
);

